/**
 * 规则包版本：只在该包的**规则内容**变化时升位。
 *
 * 用途只有一个——档案 diff 的归因。当两次评估结论不同时，需要区分：
 * - 输入变了（坐向、用事、命主）；
 * - 规则包变了（本文件升位）；
 * - 两者都变了。
 *
 * 因此升位条件必须严格：改注释、改文案、纯重构不升；改起例、改阈值、
 * 改规则包是否参与判定才升。否则归因会把「输入变化」误报成「规则变化」。
 *
 * 语义化版本：主版本=分层或口径不兼容；次版本=新增/删除规则；
 * 修订版本=修正既有规则的判定。
 */
export const RULE_PACK_VERSION = '1.0.0'

/**
 * 历史档案（schemaVersion=1）没有记录规则包版本。
 *
 * 不使用 `1.0.0` 冒充：那会让 diff 得出「规则没变」的错误归因。
 * 也不使用空串：空串容易被 `if (!version)` 当成「无版本」静默通过。
 */
export const LEGACY_RULE_PACK_VERSION = 'legacy-unrecorded'
